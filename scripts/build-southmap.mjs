/**
 * Builds content/south-india.json: SVG paths for the About page map of the
 * states MANZZA serves (from site.config serviceRegions) and their neighbours.
 *
 *   NE_DIR=/path/to/natural-earth-vector/geojson node scripts/build-southmap.mjs
 *
 * Source: Natural Earth ne_10m_admin_1_states_provinces (public domain).
 */
import fs from 'node:fs';
import path from 'node:path';
import { geoMercator, geoPath } from 'd3-geo';
import config from '../site.config.js';

const root = path.resolve(import.meta.dirname, '..');
const NE = process.env.NE_DIR;
if (!NE) throw new Error('Set NE_DIR to natural-earth-vector/geojson (see header)');

const served = config.company.serviceRegions;
const context = ['Kerala', 'Goa', 'Maharashtra', 'Chhattisgarh', 'Odisha', 'Puducherry'];
const all = JSON.parse(fs.readFileSync(path.join(NE, 'ne_10m_admin_1_states_provinces.geojson'), 'utf8'))
  .features.filter((f) => f.properties.adm0_a3 === 'IND');
const pick = (names) => names.map((n) => {
  const f = all.find((x) => x.properties.name === n);
  if (!f) throw new Error(`missing state ${n}`);
  return f;
});
const servedF = pick(served), contextF = pick(context);

const W = 460;
const frame = { type: 'FeatureCollection', features: servedF };
const projection = geoMercator().fitWidth(W - 40, frame);
const [[, y0], [, y1]] = geoPath(projection).bounds(frame);
projection.translate([projection.translate()[0] + 20, projection.translate()[1] - y0 + 20]);
const H = Math.round(y1 - y0 + 40);
projection.clipExtent([[-4, -4], [W + 4, H + 4]]);

// drop points closer than ~1px: the map is shown at roughly this size
const simplify = (d) => d.replace(/([ML])(-?[\d.]+),(-?[\d.]+)/g, (m, c, x, y) => `${c}${(+x).toFixed(1)},${(+y).toFixed(1)}`);
const thin = (geom) => {
  const step = (ring) => {
    const out = [];
    let last = null;
    for (const p of ring) {
      const q = projection(p);
      if (!last || Math.hypot(q[0] - last[0], q[1] - last[1]) > 1.6) { out.push(p); last = q; }
    }
    if (out.length > 2) out.push(out[0]);
    return out;
  };
  const polys = geom.type === 'Polygon' ? [geom.coordinates] : geom.coordinates;
  const kept = polys.map((poly) => poly.map(step).filter((r) => r.length > 3)).filter((p) => p.length);
  return { type: 'MultiPolygon', coordinates: kept };
};
const gp = geoPath(projection);
const shape = (f) => simplify(gp(thin(f.geometry)));

const BLR = [77.5946, 12.9716];
const out = {
  _readme: 'Generated by scripts/build-southmap.mjs from Natural Earth. Do not edit by hand.',
  width: W,
  height: H,
  served: servedF.map((f) => {
    const [cx, cy] = gp.centroid(f);
    return { name: f.properties.name, d: shape(f), cx: +cx.toFixed(1), cy: +cy.toFixed(1) };
  }),
  context: contextF.map((f) => ({ name: f.properties.name, d: shape(f) })),
  blr: projection(BLR).map((v) => +v.toFixed(1)),
};
fs.writeFileSync(path.join(root, 'content', 'south-india.json'), JSON.stringify(out));
console.log('south-india.json', W, 'x', H, (JSON.stringify(out).length / 1024).toFixed(1) + ' KB');
